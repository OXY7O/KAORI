from __future__ import annotations

from collections import Counter
from typing import Any

from openpyxl.chart import BarChart, Reference
from openpyxl.styles import Font
from openpyxl.worksheet.worksheet import Worksheet

from app.reports.export.inventory_common import InventoryExportDataset
from app.reports.export.tabular import protect_spreadsheet_formula, serialize_tabular_value
from app.reports.export.xlsx.standard import INVENTORY_OVERVIEW_SHEET
from app.reports.export.xlsx.style import (
    configure_sheet_page,
    set_footer,
    style_body,
    style_header,
    style_subtitle,
    style_summary_label,
    style_summary_value,
    style_title,
)

_VISUAL_HEADER_ROW = 18


def build_inventory_overview_sheet(sheet: Worksheet, dataset: InventoryExportDataset) -> None:
    _write_overview_header(sheet, dataset)
    _write_overview_kpis(sheet, dataset)
    _write_overview_context(sheet, dataset)
    _write_overview_navigation(sheet)
    chart_end_row = _write_overview_visual(sheet, dataset)

    for column, width in {'A': 28, 'B': 18, 'C': 4, 'D': 18, 'E': 18, 'F': 4, 'G': 18, 'H': 18}.items():
        sheet.column_dimensions[column].width = width
    sheet.freeze_panes = 'A5'
    configure_sheet_page(
        sheet,
        print_area=f'A1:H{max(30, chart_end_row)}',
        print_title_rows='$1:$2',
        orientation='landscape',
        fit_to_width=1,
    )
    set_footer(sheet, str(dataset.context.report_id))


def _write_overview_header(sheet: Worksheet, dataset: InventoryExportDataset) -> None:
    sheet.merge_cells('A1:H1')
    title = sheet['A1']
    title.value = f'KAORI — {dataset.profile.title} Overview'
    style_title(title)
    sheet.row_dimensions[1].height = 30

    sheet.merge_cells('A2:H2')
    subtitle = sheet['A2']
    subtitle.value = 'Workbook landing page for scope, key metrics, navigation, and evidence-backed visuals.'
    style_subtitle(subtitle)
    sheet.row_dimensions[2].height = 26
    sheet.row_dimensions[3].height = 8


def _write_overview_kpis(sheet: Worksheet, dataset: InventoryExportDataset) -> None:
    profile = dataset.profile
    context = dataset.context
    sheet.merge_cells('A4:H4')
    sheet['A4'] = 'Key Metrics'
    style_summary_label(sheet['A4'])
    sheet.row_dimensions[4].height = 22

    kpis = (
        ('Records', dataset.row_count),
        ('Columns', len(profile.columns)),
        ('Identity Fields', len(profile.identity_columns)),
        ('Data Cut-off', serialize_tabular_value(context.data_cutoff) or 'Not Available'),
    )
    for index, (label, value) in enumerate(kpis):
        start_col = 1 + (index * 2)
        label_cell = sheet.cell(row=5, column=start_col, value=label)
        value_cell = sheet.cell(row=6, column=start_col, value=value)
        sheet.merge_cells(start_row=5, start_column=start_col, end_row=5, end_column=start_col + 1)
        sheet.merge_cells(start_row=6, start_column=start_col, end_row=6, end_column=start_col + 1)
        style_summary_label(label_cell)
        style_summary_value(value_cell)
    sheet.row_dimensions[5].height = 22
    sheet.row_dimensions[6].height = 32


def _write_overview_context(sheet: Worksheet, dataset: InventoryExportDataset) -> None:
    context = dataset.context
    sheet.merge_cells('A8:D8')
    sheet['A8'] = 'General Information'
    style_summary_label(sheet['A8'])
    sheet.row_dimensions[8].height = 22

    scope_rows = (
        ('Report Reference', str(context.report_id)),
        (context.scope_label, context.cluster_scope),
        ('Namespace', context.namespace_scope),
        ('Reporting Period', context.period_label),
        ('Source', context.source_label),
        ('Generated By', context.generated_by),
        ('Classification', context.classification),
    )
    for row_index, (label, value) in enumerate(scope_rows, start=9):
        sheet.cell(row=row_index, column=1, value=label)
        sheet.merge_cells(start_row=row_index, start_column=2, end_row=row_index, end_column=4)
        sheet.cell(row=row_index, column=2, value=_overview_value(value))
        style_summary_label(sheet.cell(row=row_index, column=1))
        style_body(sheet.cell(row=row_index, column=2))
        sheet.row_dimensions[row_index].height = 22


def _write_overview_navigation(sheet: Worksheet) -> None:
    sheet.merge_cells('F8:H8')
    sheet['F8'] = 'Workbook Navigation'
    style_summary_label(sheet['F8'])

    navigation = tuple(
        target_sheet for target_sheet in sheet.parent.sheetnames if target_sheet != INVENTORY_OVERVIEW_SHEET
    )
    for row_index, target_sheet in enumerate(navigation, start=9):
        sheet.merge_cells(start_row=row_index, start_column=6, end_row=row_index, end_column=8)
        cell = sheet.cell(row=row_index, column=6, value=target_sheet)
        cell.hyperlink = f"#'{target_sheet}'!A1"
        style_body(cell)
        cell.font = Font(name='Aptos', size=10, bold=True, color='7C3AED', underline='single')
        sheet.row_dimensions[row_index].height = 22


def _write_overview_visual(sheet: Worksheet, dataset: InventoryExportDataset) -> int:
    sheet.merge_cells(start_row=_VISUAL_HEADER_ROW, start_column=1, end_row=_VISUAL_HEADER_ROW, end_column=8)
    sheet.cell(row=_VISUAL_HEADER_ROW, column=1, value='Visual Summary')
    style_summary_label(sheet.cell(row=_VISUAL_HEADER_ROW, column=1))
    sheet.row_dimensions[_VISUAL_HEADER_ROW].height = 22

    chart = dataset.profile.overview_chart
    data_header_row = _VISUAL_HEADER_ROW + 1
    data_start_row = data_header_row + 1
    if not dataset.rows:
        return _write_visual_message(
            sheet,
            data_header_row,
            'No committed records are available for an evidence-backed visual summary.',
        )

    rows = _collect_chart_rows(dataset)
    if not rows:
        return _write_visual_message(
            sheet,
            data_header_row,
            'No chartable numeric evidence is available for this workbook scope.',
        )

    category_column = next(
        (column for column in dataset.profile.columns if column.key == chart.category_key),
        None,
    )
    value_column = next(
        (column for column in dataset.profile.columns if column.key == chart.value_key),
        None,
    )
    category_label = category_column.label if category_column is not None else 'Category'
    value_label = 'Records' if chart.aggregation == 'count' else (value_column.label if value_column else 'Value')
    number_format = (
        '#,##0'
        if chart.aggregation == 'count'
        else ((value_column.number_format if value_column is not None else None) or '#,##0.00')
    )

    sheet.cell(row=data_header_row, column=1, value=category_label)
    sheet.cell(row=data_header_row, column=2, value=value_label)
    style_header(sheet.cell(row=data_header_row, column=1))
    style_header(sheet.cell(row=data_header_row, column=2))
    for row_index, (category, value) in enumerate(rows, start=data_start_row):
        sheet.cell(row=row_index, column=1, value=category)
        sheet.cell(row=row_index, column=2, value=value)
        style_body(sheet.cell(row=row_index, column=1), alternate=row_index % 2 == 0)
        style_body(sheet.cell(row=row_index, column=2), alternate=row_index % 2 == 0)
        sheet.cell(row=row_index, column=2).number_format = number_format

    end_row = data_header_row + len(rows)
    _add_overview_bar_chart(sheet, dataset, data_header_row, data_start_row, end_row)
    return end_row


def _collect_chart_rows(dataset: InventoryExportDataset) -> list[tuple[str, int | float]]:
    chart = dataset.profile.overview_chart

    if chart.aggregation == 'count':
        counts: Counter[str] = Counter()
        for row in dataset.rows:
            category = row.get(chart.category_key)
            if category in (None, ''):
                continue
            counts[_safe_text_value(category)] += 1
        rows = list(counts.items())
        rows.sort(key=lambda item: (-item[1], item[0].casefold()))
        return rows[: max(1, chart.top_n)]

    if chart.aggregation != 'value' or chart.value_key is None:
        raise ValueError(f'Unsupported XLSX overview chart aggregation: {chart.aggregation!r}.')

    rows: list[tuple[str, float]] = []
    for row in dataset.rows:
        category = row.get(chart.category_key)
        value = row.get(chart.value_key)
        if category in (None, '') or not isinstance(value, (int, float)):
            continue
        rows.append((_safe_text_value(category), float(value)))
    rows.sort(key=lambda item: (-item[1], item[0].casefold()))
    return rows[: max(1, chart.top_n)]


def _add_overview_bar_chart(
    sheet: Worksheet,
    dataset: InventoryExportDataset,
    data_header_row: int,
    data_start_row: int,
    end_row: int,
) -> None:
    chart = dataset.profile.overview_chart
    values = Reference(sheet, min_col=2, min_row=data_header_row, max_row=end_row)
    categories = Reference(sheet, min_col=1, min_row=data_start_row, max_row=end_row)
    visual = BarChart()
    visual.type = 'bar'
    visual.style = 10
    visual.title = chart.title
    visual.height = 7.5
    visual.width = 14.5
    visual.add_data(values, titles_from_data=True)
    visual.set_categories(categories)
    visual.legend = None
    sheet.add_chart(visual, f'D{data_header_row}')


def _write_visual_message(sheet: Worksheet, row: int, message: str) -> int:
    sheet.merge_cells(start_row=row, start_column=1, end_row=row, end_column=8)
    sheet.cell(row=row, column=1, value=message)
    style_body(sheet.cell(row=row, column=1))
    return row


def _safe_text_value(value: Any) -> str:
    return protect_spreadsheet_formula(str(value))


def _overview_value(value: Any) -> str:
    if value is None or value == '':
        return 'Not Available'
    return _safe_text_value(value)
